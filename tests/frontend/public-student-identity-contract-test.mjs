import fs from 'node:fs';
import assert from 'node:assert/strict';
const portal=fs.readFileSync(new URL('../../portal.php',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('../../assets/student-app.css',import.meta.url),'utf8');
const parent=fs.readFileSync(new URL('../../parent.php',import.meta.url),'utf8');
const organizationAdmin=fs.readFileSync(new URL('../../organization-admin.php',import.meta.url),'utf8');
const masterAdmin=fs.readFileSync(new URL('../../admin.php',import.meta.url),'utf8');
const portalLib=fs.readFileSync(new URL('../../portal-lib.php',import.meta.url),'utf8');
assert.match(portal,/Your YUVA Identity/);
assert.match(portal,/Your YUVA ID is permanent/);
assert.match(portal,/public_student_identity/);
assert.match(portal,/avatar_code/);
assert.match(portal,/csrf_field/);
assert.doesNotMatch(portal,/name="(?:email|phone|date_of_birth|address)"[^>]*public/i);
assert.match(portal,/public_student_identity\(\$studentId\)/, 'Student identity must resolve from the authenticated canonical YUVA ID');
assert.match(parent,/public_student_identity\(\$studentId\)/, 'Parent identity must resolve from the linked canonical YUVA ID, not the parent wrapper array');
assert.match(organizationAdmin,/public_student_identity\(\(string\)\$studentId\)/, 'Organization roster identity must resolve from its scoped canonical YUVA ID');
assert.match(masterAdmin,/public_student_identity\(\(string\)\$studentId\)/, 'Master Admin identity must resolve from the canonical YUVA ID');
assert.match(portalLib,/function public_student_identity\(string \$yuvaId\): array/, 'Public identity helper must accept only an explicit canonical YUVA ID');
assert.doesNotMatch(portalLib,/function public_student_identity\(array\|string/, 'Public identity helper must not guess among arbitrary student-array shapes');
assert.match(css,/identity-editor-grid/);
assert.match(css,/@media\(max-width:760px\)/);
console.log('Public student identity frontend contract: PASS');
